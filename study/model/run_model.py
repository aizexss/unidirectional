"""Exact finite-model analysis of snapshot provenance; Python standard library.

This is a computation over declared abstract states, not an AIMI measurement.
Every numerical result is regenerated by running this file.  No random sampling,
network traffic, source trace, or hardware-specific timing is involved.
"""
from __future__ import annotations

import csv
import hashlib
import itertools
import json
import math
from collections import Counter
from pathlib import Path

HERE = Path(__file__).resolve().parent
CATALOG = ((0, 0), (1, 1))
VERDICTS = ("coherent", "mixed", "ambiguous", "out_of_model", "unavailable")


def monitor(x, y, *, labels=None, group="unknown", catalog=CATALOG):
    """Pointwise observer receives public values and permitted evidence only.

    labels is None, or a pair of trusted, value-bound origin identifiers.
    group is independently trusted common/different-origin evidence.  The public
    model permits any number of generations of each catalog vector; identifiers
    carry equality information, not access to the private source history.
    """
    if x is None or y is None:
        return "unavailable", None, None
    equal_allowed = different_allowed = True
    if labels is not None:
        equal_allowed = labels[0] == labels[1]
        different_allowed = not equal_allowed
    if group == "same":
        different_allowed = False
    elif group == "different":
        equal_allowed = False
    elif group != "unknown":
        raise ValueError(group)
    cx = {s for s in catalog if s[0] == x}
    cy = {s for s in catalog if s[1] == y}
    pc = equal_allowed and bool(cx & cy)
    pm = different_allowed and bool(cx) and bool(cy)
    verdict = {(True, True): "ambiguous", (True, False): "coherent",
               (False, True): "mixed", (False, False): "out_of_model"}[(pc, pm)]
    return verdict, pc, pm


def independent_oracle(x, y, *, labels=None, group="unknown"):
    """Enumerate origin equality and complete states, independently of formula.

    Two abstract origins suffice to witness both possible equality relations.
    An identifier's literal value has no semantics beyond its equality class.
    """
    if x is None or y is None:
        return "unavailable", None, None
    possibilities = set()
    for ox, oy in itertools.product(range(2), repeat=2):
        same = ox == oy
        if labels is not None and same != (labels[0] == labels[1]):
            continue
        if group == "same" and not same:
            continue
        if group == "different" and same:
            continue
        for state0, state1 in itertools.product(CATALOG, repeat=2):
            by_origin = (state0, state1)
            if by_origin[ox][0] == x and by_origin[oy][1] == y:
                possibilities.add("coherent" if same else "mixed")
    pc, pm = "coherent" in possibilities, "mixed" in possibilities
    if not possibilities:
        verdict = "out_of_model"
    elif len(possibilities) == 2:
        verdict = "ambiguous"
    else:
        verdict = next(iter(possibilities))
    return verdict, pc, pm


def write_csv(name, rows):
    with (HERE / name).open("w", encoding="utf-8-sig", newline="") as handle:
        writer = csv.DictWriter(handle, fieldnames=list(rows[0]))
        writer.writeheader()
        writer.writerows(rows)


def validate_monitor():
    rows = []
    label_options = (None, ("A", "A"), ("A", "B"))
    for x, y, labels, group in itertools.product(
            (None, -1, 0, 1, 2), (None, -1, 0, 1, 2),
            label_options, ("unknown", "same", "different")):
        actual = monitor(x, y, labels=labels, group=group)
        expected = independent_oracle(x, y, labels=labels, group=group)
        assert actual == expected, (x, y, labels, group, actual, expected)
        rows.append(dict(x=x, y=y, labels=str(labels), group=group,
                         verdict=actual[0], PC=actual[1], PM=actual[2],
                         agrees_with_enumerated_explanations=1))
    write_csv("oracle_checks.csv", rows)
    return len(rows)


def state_values(history, origins):
    return tuple(None if o == 0 else history[o - 1] for o in origins)


def truth(origins):
    if 0 in origins:
        return "unavailable"
    return "coherent" if origins[0] == origins[1] else "mixed"


def summarize_states(n=3, output=True):
    rows, summary = [], []
    for publication in ("R0", "R1"):
        origins_set = (tuple(itertools.product(range(n + 1), repeat=2))
                       if publication == "R0" else tuple((i, i) for i in range(n + 1)))
        for profile in ("V", "G", "I"):
            counts, trues = Counter(), Counter()
            errors = refined_checks = hidden_mixed = 0
            naive_false_coherent = 0
            for history in itertools.product((0, 1), repeat=n):
                for origins in origins_set:
                    x, y = state_values(history, origins)
                    reference = truth(origins)
                    group = "same" if profile == "G" and publication == "R1" else "unknown"
                    labels = origins if profile == "I" and reference != "unavailable" else None
                    verdict, pc, pm = monitor(x, y, labels=labels, group=group)
                    counts[verdict] += 1
                    trues[reference] += 1
                    if verdict in ("coherent", "mixed"):
                        errors += int(verdict != reference)
                    hidden_mixed += int(reference == "mixed" and verdict == "ambiguous")
                    naive_false_coherent += int(reference == "mixed" and (x, y) in CATALOG)
                    basic = monitor(x, y)[0]
                    if basic in ("coherent", "mixed"):
                        assert verdict == basic
                        refined_checks += 1
                    assert verdict != "out_of_model"
                    rows.append(dict(n=n, publication=publication, observation_profile=profile,
                                     source_history="".join(map(str, history)),
                                     x_origin=origins[0], y_origin=origins[1], x=x, y=y,
                                     group=group, labels_visible=int(labels is not None),
                                     reference=reference, verdict=verdict, PC=pc, PM=pm))
            assert errors == 0
            total = sum(counts.values())
            complete = total - trues["unavailable"]
            defined = counts["coherent"] + counts["mixed"]
            summary.append(dict(n=n, publication=publication, observation_profile=profile,
                                total=total, complete=complete,
                                reference_coherent=trues["coherent"],
                                reference_mixed=trues["mixed"],
                                **{v: counts[v] for v in VERDICTS},
                                coverage_all=defined / total,
                                coverage_complete=defined / complete,
                                complete_state_share=complete / total,
                                hidden_mixed=hidden_mixed, confident_errors=errors,
                                confident_comparisons=defined,
                                confident_error_fraction=(errors / defined if defined else None),
                                refined_defined_verdict_checks=refined_checks,
                                naive_catalog_false_coherent=naive_false_coherent))
    if output:
        write_csv("all_states_n3.csv", rows)
        write_csv("state_summary_n3.csv", summary)
    return summary


def delivery_sequences(message_count):
    """Each message has 0..1 deliveries, in arbitrary order.

    Every distinct word over this bounded multiset is emitted once.  Arbitrary
    ordering/loss is permitted.  No clock or likelihood is attached to a word.
    """
    def extend(word, counts):
        yield tuple(word)
        for message in range(message_count):
            if counts[message] == 0:
                counts[message] += 1
                word.append(message)
                yield from extend(word, counts)
                word.pop()
                counts[message] -= 1
    yield from extend([], [0] * message_count)


def publish(state, message, publication):
    if publication == "R1":
        origin = message + 1
        return (origin, origin)
    origin, field = divmod(message, 2)
    result = list(state)
    result[field] = origin + 1
    return tuple(result)


def exhaustive_schedules(n=3):
    rows = []
    for publication, message_count in (("R0", 2 * n), ("R1", n)):
        reachable = set()
        words = scenarios = sampled_states = 0
        violating_r1 = 0
        for word in delivery_sequences(message_count):
            words += 1
            # None means no reset; 0..len(word) means one atomic clear before
            # the indexed next delivery (or after all deliveries at len).
            for reset_position in (None, *range(len(word) + 1)):
                scenarios += 1
                state = (0, 0)
                reachable.add(state)
                sampled_states += 1
                for position in range(len(word) + 1):
                    if position == reset_position:
                        state = (0, 0)
                        reachable.add(state)
                        sampled_states += 1
                    if position < len(word):
                        state = publish(state, word[position], publication)
                        reachable.add(state)
                        sampled_states += 1
                        if publication == "R1" and state[0] != state[1]:
                            violating_r1 += 1
        expected = (set(itertools.product(range(n + 1), repeat=2))
                    if publication == "R0" else {(i, i) for i in range(n + 1)})
        assert reachable == expected, (publication, reachable, expected)
        assert violating_r1 == 0
        expected_words = sum(math.perm(message_count, k) for k in range(message_count + 1))
        assert words == expected_words
        rows.append(dict(publication=publication, logical_messages=message_count,
                         delivery_words=words,
                         words_and_reset_positions=scenarios,
                         recorded_states_with_repetition=sampled_states,
                         distinct_origin_states=len(reachable),
                         violating_r1_states=(violating_r1 if publication == "R1" else None),
                         source_histories_checked_separately=2 ** n))
    write_csv("schedule_enumeration.csv", rows)
    return rows


def control_cases():
    cases = [
        ("same_value_common_origin", (0, 0, 0), (1, 1), "unknown"),
        ("same_value_distinct_origins", (0, 0, 0), (1, 2), "unknown"),
        ("ABA_distinct_origins", (0, 1, 0), (3, 1), "unknown"),
        ("unequal_values_distinct_origins", (0, 1, 0), (1, 2), "unknown"),
        ("complete_old_snapshot", (0, 1, 0), (1, 1), "same"),
        ("one_field_missing", (0, 1, 0), (0, 2), "unknown"),
    ]
    rows = []
    for name, history, origins, group in cases:
        x, y = state_values(history, origins)
        rows.append(dict(case=name, history="".join(map(str, history)),
                         x=x, y=y, x_origin=origins[0], y_origin=origins[1],
                         reference=truth(origins), values_only=monitor(x, y)[0],
                         labels=monitor(x, y, labels=origins)[0],
                         grouping=monitor(x, y, group=group)[0]))
    write_csv("control_cases.csv", rows)
    diagnostic_rows = []
    for name, x, y, labels, group, expected in [
        ("outside_catalog", 2, 0, None, "unknown", "out_of_model"),
        ("equal_labels_incompatible_values", 0, 1, ("A", "A"), "unknown", "out_of_model"),
        ("conflicting_evidence", 0, 0, ("A", "B"), "same", "out_of_model"),
        ("known_different_equal_values", 0, 0, None, "different", "mixed"),
        ("missing_field_precedes_model_check", None, 2, None, "unknown", "unavailable"),
    ]:
        actual = monitor(x, y, labels=labels, group=group)[0]
        assert actual == expected
        diagnostic_rows.append(dict(case=name, x=x, y=y, labels=str(labels), group=group,
                                    verdict=actual, expected=expected))
    write_csv("diagnostic_cases.csv", diagnostic_rows)

    # A deliberately false premise may produce false confidence, not necessarily
    # out_of_model: equal values conceal mixed provenance in this counterexample.
    false_group = monitor(0, 0, group="same")[0]
    assert false_group == "coherent"
    write_csv("violated_assumption_control.csv", [dict(
        case="false_same_origin_grouping", history="000", x_origin=1, y_origin=2,
        x=0, y=0, actual="mixed", supplied_group="same", verdict=false_group,
        actual_explanation_in_Omega=0,
        interpretation="False premise; excluded from correct-profile error denominator")])

    duplicate_rows = []
    # Duplicates preserve the R1 invariant but can overwrite just one R0 field.
    for publication, word in (("R0", (0, 1, 2, 3, 0)), ("R1", (0, 1, 0))):
        state = (0, 0)
        for step, message in enumerate(word, 1):
            state = publish(state, message, publication)
            duplicate_rows.append(dict(publication=publication, step=step, message=message,
                                       x_origin=state[0], y_origin=state[1],
                                       reference=truth(state)))
            if publication == "R1":
                assert state[0] == state[1]
    write_csv("duplicate_trace_controls.csv", duplicate_rows)


def catalog_sensitivity(n=3):
    rows = []
    catalogs = (("G_diagonal", CATALOG), ("G_full_binary", tuple(itertools.product((0, 1), repeat=2))))
    for publication in ("R0", "R1"):
        origins_set = (tuple(itertools.product(range(n + 1), repeat=2))
                       if publication == "R0" else tuple((i, i) for i in range(n + 1)))
        for catalog_name, catalog in catalogs:
            counts = Counter()
            for history in itertools.product((0, 1), repeat=n):
                for origins in origins_set:
                    x, y = state_values(history, origins)
                    counts[monitor(x, y, catalog=catalog)[0]] += 1
            rows.append(dict(publication=publication, public_catalog=catalog_name,
                             actual_source_catalog="G_diagonal", observation_profile="V",
                             total=sum(counts.values()), **{v: counts[v] for v in VERDICTS}))
    assert rows[1]["ambiguous"] == 72 and rows[1]["mixed"] == 0
    write_csv("catalog_sensitivity.csv", rows)
    return rows


def formulas(n):
    """Closed counts under uniform counting of histories and physical states."""
    h = 2 ** n
    return {
        "R0_total": h * (n + 1) ** 2,
        "R0_complete": h * n ** 2,
        "R0_coherent": h * n,
        "R0_mixed": h * n * (n - 1),
        "R0_unavailable": h * (2 * n + 1),
        "R0_V_mixed": (h // 2) * n * (n - 1),
        "R0_V_ambiguous": h * n + (h // 2) * n * (n - 1),
        "R1_total": h * (n + 1),
        "R1_complete_coherent": h * n,
        "R1_unavailable": h,
    }


def main():
    oracle_count = validate_monitor()
    summary = summarize_states()
    sensitivity = []
    for n in range(2, 7):
        result = summarize_states(n, output=False)
        f = formulas(n)
        r0v = next(r for r in result if r["publication"] == "R0" and r["observation_profile"] == "V")
        r1g = next(r for r in result if r["publication"] == "R1" and r["observation_profile"] == "G")
        assert r0v["total"] == f["R0_total"]
        assert r0v["complete"] == f["R0_complete"]
        assert r0v["reference_mixed"] == f["R0_mixed"]
        assert r0v["mixed"] == f["R0_V_mixed"]
        assert r0v["ambiguous"] == f["R0_V_ambiguous"]
        assert r1g["total"] == f["R1_total"]
        assert r1g["coherent"] == f["R1_complete_coherent"]
        sensitivity.extend(result)
    write_csv("sensitivity_n2_to_n6.csv", sensitivity)
    schedules = exhaustive_schedules()
    control_cases()
    catalog_results = catalog_sensitivity()
    report = dict(
        study_type="Exact finite-state computation; not hardware or network measurement",
        n_generations=3, public_catalog=CATALOG,
        histories=8, origin_zero="field absent; no origin",
        enumeration_weighting="Each declared history-state pair counted once; not a probability model",
        source_history_visible_to_monitor=False,
        profile_V="Values only; no origin labels or grouping",
        profile_G="Values plus proven same-origin grouping for R1; R0 grouping unknown",
        profile_I="Values plus trusted origin labels atomically bound to each field",
        oracle_checks=oracle_count, oracle_disagreements=0,
        summary=summary, schedules=schedules, catalog_sensitivity=catalog_results,
        limitations=[
            "Binary diagonal catalog, two fields, three generations in main finite enumeration",
            "Arbitrary delivery permutations/losses; each message at most once in exhaustive schedules; duplicates are separate illustrative controls",
            "Zero or one receiver restart, atomically clearing all fields",
            "Authenticity and correctness of origin/value binding are assumptions",
            "No timing, age, bandwidth, loss-rate, restart-duration or hardware-performance estimates",
            "State-space shares are not prevalence estimates or independent experimental observations",
            "Out-of-model controls are deliberate diagnostics, not observed AIMI failures",
        ])
    (HERE / "results.json").write_text(json.dumps(report, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    hashes = []
    for p in sorted(HERE.iterdir()):
        if p.is_file() and p.name != "SHA256SUMS.txt":
            hashes.append(f"{hashlib.sha256(p.read_bytes()).hexdigest()}  {p.name}")
    (HERE / "SHA256SUMS.txt").write_text("\n".join(hashes) + "\n", encoding="utf-8")
    print(json.dumps({"oracle_checks": oracle_count, "summary": summary, "schedules": schedules}, ensure_ascii=False, indent=2))


if __name__ == "__main__":
    main()
